//! Which ORM generated a capture, from the shape of its SQL. Each statement votes
//! for the ORM whose signature it matches; the majority wins if it's clear.

use std::collections::HashMap;

use crate::model::{FingerprintStat, Orm};

/// Share of signed statements one ORM needs to be named.
const MAJORITY: f64 = 0.6;

pub fn recognize(stats: &[FingerprintStat]) -> Option<Orm> {
    let mut votes: HashMap<Orm, u32> = HashMap::new();
    for s in stats {
        if let Some(orm) = signature(&s.sample_sql) {
            *votes.entry(orm).or_default() += s.calls;
        }
    }
    let total: u32 = votes.values().sum();
    let (orm, n) = votes.into_iter().max_by_key(|(_, n)| *n)?;
    (f64::from(n) / f64::from(total) >= MAJORITY).then_some(orm)
}

/// The ORM a single statement looks generated by.
fn signature(sql: &str) -> Option<Orm> {
    let s = sql.trim();
    // Prisma qualifies every column with the schema ("public"."User"."id") and
    // never ends with ';'.
    if s.contains("\"public\".\"") && !s.ends_with(';') {
        return Some(Orm::Prisma);
    }
    // TypeORM: "User"."id" AS "User_id".
    if aliases(s).any(|(qualified, alias)| alias.contains('_') && qualified.replace("\".\"", "_") == alias) {
        return Some(Orm::TypeOrm);
    }
    // Sequelize ends statements with ';', aliases the table as the model
    // ("users" AS "User") and eager-loaded columns with dots ("items.id").
    if s.ends_with(';') && (aliases(s).any(|(_, alias)| alias.contains('.')) || model_alias(s)) {
        return Some(Orm::Sequelize);
    }
    if s.starts_with("INSERT INTO \"") && s.contains("VALUES (DEFAULT,") && s.ends_with(';') {
        return Some(Orm::Sequelize);
    }
    // Active Record: SELECT "orders".* FROM "orders".
    if s.contains("\".* FROM \"") {
        return Some(Orm::ActiveRecord);
    }
    // Hibernate 6 aliases tables as u1_0; Hibernate 5 columns as id1_0_.
    if s.contains("1_0.") || s.contains("0_.") {
        return Some(Orm::Hibernate);
    }
    // SQLAlchemy: users.id AS users_id (unquoted).
    if s.contains(" AS ") && s.split_whitespace().collect::<Vec<_>>().windows(3).any(|w| {
        w[1] == "AS" && w[0].trim_end_matches(',').replace('.', "_") == w[2].trim_end_matches(',')
    }) {
        return Some(Orm::SqlAlchemy);
    }
    // Django: fully qualified quoted columns, no aliases, no semicolon, LIMIT 21 for reprs.
    if s.starts_with("SELECT \"") && s.contains("\".\"") && !s.contains(" AS ") && !s.ends_with(';') {
        return Some(Orm::Django);
    }
    None
}

/// `"x"."y" AS "alias"` pairs: (`x"."y`, `alias`).
fn aliases(s: &str) -> impl Iterator<Item = (String, String)> + '_ {
    s.match_indices("\" AS \"").filter_map(move |(i, _)| {
        let before = &s[..i];
        let start = before.rfind([' ', ',', '('])? + 1;
        let qualified = before[start..].trim_start_matches('"').to_string();
        let after = &s[i + 6..];
        let alias = after[..after.find('"')?].to_string();
        Some((qualified, alias))
    })
}

/// `FROM "users" AS "User"`: a lowercase table aliased to a capitalized model name.
fn model_alias(s: &str) -> bool {
    s.match_indices(" AS \"").any(|(i, _)| {
        let table_quoted = s[..i].ends_with('"');
        let alias_capitalized = s[i + 5..].chars().next().is_some_and(char::is_uppercase);
        table_quoted && alias_capitalized
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn signatures() {
        let cases = [
            (r#"SELECT "id", "email" FROM "users" AS "User" WHERE "User"."id" = 1;"#, Some(Orm::Sequelize)),
            (
                r#"SELECT "Order"."id", "items"."id" AS "items.id" FROM "orders" AS "Order" LEFT OUTER JOIN "order_items" AS "items" ON "Order"."id" = "items"."order_id";"#,
                Some(Orm::Sequelize),
            ),
            (r#"INSERT INTO "events" ("id","kind") VALUES (DEFAULT,$1) RETURNING "id","kind";"#, Some(Orm::Sequelize)),
            (
                r#"SELECT "public"."User"."id" FROM "public"."User" WHERE "public"."User"."id" = $1 LIMIT $2 OFFSET $3"#,
                Some(Orm::Prisma),
            ),
            (r#"SELECT "User"."id" AS "User_id" FROM "user" "User""#, Some(Orm::TypeOrm)),
            (r#"SELECT "orders".* FROM "orders" WHERE "orders"."user_id" = $1"#, Some(Orm::ActiveRecord)),
            ("SELECT users.id AS users_id, users.name AS users_name FROM users", Some(Orm::SqlAlchemy)),
            (r#"SELECT "shop_order"."id", "shop_order"."total" FROM "shop_order" LIMIT 21"#, Some(Orm::Django)),
            ("select u1_0.id from users u1_0", Some(Orm::Hibernate)),
            ("SELECT 1", None),
        ];
        for (sql, want) in cases {
            assert_eq!(signature(sql), want, "{sql}");
        }
    }
}
